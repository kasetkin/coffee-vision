B_NULL = 4000
RNG = np.random.default_rng(20261123)

lines: list[str] = []


def out(s: str = "") -> None:
    lines.append(s)
    print(s)


def exp_dir(e: int) -> Path:
    return sorted(EXP.glob(f"exp{e}__*"))[0]


def metrics(e: int) -> dict:
    return json.loads((exp_dir(e) / "metrics.json").read_text())


def seed_of(e: int) -> int:
    return json.loads((exp_dir(e) / "config.json").read_text())["seed"]


def load_preds(e: int, split: str = "test"):
    rows = list(csv.DictReader(open(exp_dir(e) / f"predictions_{split}.csv")))
    classes = metrics(e)["class_ids"]
    ci = {c: i for i, c in enumerate(classes)}
    y = np.array([ci[r["true_label"]] for r in rows])
    p = np.array([ci[r["pred_label"]] for r in rows])
    keys = [(r["true_label"], r["folder_id"], r["photo"]) for r in rows]
    return classes, y, p, keys


def f1s(y: np.ndarray, p: np.ndarray, k: int, w: np.ndarray | None = None) -> np.ndarray:
    """Per-class F1 from labels and predictions, rows weighted by w (bootstrap multiplicities)."""
    if w is None:
        w = np.ones_like(y, dtype=float)
    tp = np.bincount(y[y == p], weights=w[y == p], minlength=k)
    sup = np.bincount(y, weights=w, minlength=k)
    pred = np.bincount(p, weights=w, minlength=k)
    denom = sup + pred
    with np.errstate(invalid="ignore", divide="ignore"):
        f = np.where(denom > 0, 2 * tp / denom, 0.0)
    return f


