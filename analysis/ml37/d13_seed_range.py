"""ML-37 D13: what "the seed range" has been, and how a no-regression bar behaves under no real change.

Research for ML-37 D13 (2026-11-23). Reads the archived runs in experiments/ only; trains nothing, writes
d13_seed_range.txt next to this script.

Parts:
  A. The country-era triples (exp261-291): test and val macro-F1 range over seeds 42/123/7, the per-class F1 range,
     and the test photos per class (a patch's photo is its (folder_id, photo) pair in predictions_test.csv).
  B. Paired deltas where the record has them: P10's exp289-291 vs exp286-288 (same photos, same split), and every
     run's augmented head against its unaugmented head (same patches, metrics.json arms).
  C. A photo-level paired bootstrap of P10's pair: the test photos resampled within each class, the same draw for
     both arms, macro-F1 and per-class F1 recomputed from the archived patch predictions.
  D. A randomization null on P10's pair: for each test photo, the two arms' predictions are swapped with
     probability 1/2 (the arms are exchangeable if nothing changed), then candidate rules are applied to the three
     seeds' deltas. Their rate of firing is their false-alarm rate at P10's level of refit disagreement.
  E. Power: the same null with a real drop planted in one class: k of its test photos have every patch of the new
     arm turned to the class it is most confused with in the baseline.

    cd /workspace && PYTHONPATH=/workspace uv run python analysis/ml37/d13_seed_range.py
"""
