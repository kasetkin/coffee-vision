out("ML-37 D13: the seed range in the record, and how no-regression rules behave under no real change.")
out("Generated by analysis/ml37/d13_seed_range.py from experiments/ (read only). Metrics are patch macro-F1, as recorded.")
out()
out("A. Country-era triples, seeds 42/123/7: range (max - min) over the three seeds")
out(f"  {'triple':44s} {'test range':>22s} {'val range':>22s} {'per-class test F1 range: median, max (class)':>48s}")
pc_ranges_all = []
for name, ids in TRIPLES:
    ms = [metrics(e) for e in ids]
    t = [m["splits"]["test"]["macro_f1"] for m in ms]
    v = [m["splits"]["val"]["macro_f1"] for m in ms]
    classes = ms[0]["class_ids"]
    pcr = {}
    for c in classes:
        vals = [m["splits"]["test"]["per_class"][c]["f1"] for m in ms if c in m["splits"]["test"]["per_class"]]
        if len(vals) == 3:
            pcr[c] = max(vals) - min(vals)
    worst = max(pcr, key=pcr.get)
    pc_ranges_all.append((name, pcr))
    out(f"  {name:44s} {min(t):.4f}-{max(t):.4f} ({max(t)-min(t):.4f}) {min(v):.4f}-{max(v):.4f} ({max(v)-min(v):.4f})"
        f"   {np.median(list(pcr.values())):.3f}, {pcr[worst]:.3f} ({worst})")
allr = [max(metrics(e)["splits"]["test"]["macro_f1"] for e in ids) - min(metrics(e)["splits"]["test"]["macro_f1"] for e in ids)
        for _, ids in TRIPLES]
out(f"  test macro-F1 range over the ten triples: median {np.median(allr):.4f}, min {min(allr):.4f}, max {max(allr):.4f}")
out()
out("  Per-class test F1 range over seeds, the baseline of P10 (exp286-288), which a D13 bar would read:")
base_pcr = dict(pc_ranges_all[8][1])
for c, r in sorted(base_pcr.items(), key=lambda kv: kv[1]):
    vals = [metrics(e)["splits"]["test"]["per_class"][c]["f1"] for e in BASE]
    out(f"    {c:10s} {' '.join(f'{x:.3f}' for x in vals)}  range {r:.3f}")
out()
out("  Test photos per class per seed (160 patches a class; patches per photo = 160 / photos):")
for e in [261, 270, 276, 283, 286, 287, 288]:
    classes, y, p, keys = load_preds(e)
    ph = defaultdict(set)
    for k in keys:
        ph[k[0]].add(k)
    out(f"    exp{e} (seed {seed_of(e):>3}): " + ", ".join(f"{c} {len(ph[c])}" for c in classes))
out()

# ---------------------------------------------------------------- B
out("B. Paired deltas in the record (new - baseline, same seed)")
out("  P10, gain maps exp289-291 vs exp286-288 (same photos and split; 1,255 photos' crops swapped):")
for n, b in zip(NEW, BASE):
    mn, mb = metrics(n), metrics(b)
    out(f"    seed {seed_of(n):>3}: test {mb['splits']['test']['macro_f1']:.4f} -> {mn['splits']['test']['macro_f1']:.4f} "
        f"({mn['splits']['test']['macro_f1'] - mb['splits']['test']['macro_f1']:+.4f}); val "
        f"{mn['splits']['val']['macro_f1'] - mb['splits']['val']['macro_f1']:+.4f}")
out("  Augmented head minus unaugmented head, same run, same patches (a real but small change, ADR 0025):")
aug_test_deltas = []
aug_pc_deltas = []
for name, ids in TRIPLES[3:]:
    ds = []
    for e in ids:
        a = metrics(e)["arms"]
        dt = a["augmented"]["splits"]["test"]["macro_f1"] - a["unaugmented"]["splits"]["test"]["macro_f1"]
        ds.append(dt)
        for c, v in a["augmented"]["splits"]["test"]["per_class"].items():
            aug_pc_deltas.append(v["f1"] - a["unaugmented"]["splits"]["test"]["per_class"][c]["f1"])
    aug_test_deltas += ds
    out(f"    {name:44s} test " + " ".join(f"{d:+.4f}" for d in ds) + f"  mean {np.mean(ds):+.4f}")
aug_pc = np.abs(np.array(aug_pc_deltas))
out(f"    per-class |delta| over those runs and classes: median {np.median(aug_pc):.3f}, 90th pct {np.quantile(aug_pc, .9):.3f}, max {aug_pc.max():.3f}")
out()

# ---------------------------------------------------------------- C, D, E: P10's pair, from patch predictions
pairs = []
for n, b in zip(NEW, BASE):
    cb, yb, pb, kb = load_preds(b)
    cn, yn, pn, kn = load_preds(n)
    assert cb == cn and kb == kn, f"exp{n} and exp{b} test patches differ"
    photo_ids = {k: i for i, k in enumerate(dict.fromkeys(kb))}
    ph = np.array([photo_ids[k] for k in kb])
    ph_class = np.zeros(len(photo_ids), dtype=int)
    ph_class[ph] = yb
    pairs.append(dict(seed=seed_of(n), y=yb, pb=pb, pn=pn, ph=ph, ph_class=ph_class, classes=cb))
classes = pairs[0]["classes"]
K = len(classes)

out("C. P10's pair at patch level, and a photo-level paired bootstrap (test photos resampled within class, the same")
out(f"   draw for both arms, {B_BOOT} draws per seed; the mean over the three seeds is the statistic)")
for pr in pairs:
    dis = np.mean(pr["pb"] != pr["pn"])
    out(f"    seed {pr['seed']:>3}: {len(pr['y'])} patches, {pr['ph'].max() + 1} photos; the arms disagree on "
        f"{dis:.1%} of patches; macro-F1 {f1s(pr['y'], pr['pb'], K).mean():.4f} -> {f1s(pr['y'], pr['pn'], K).mean():.4f}")

boot_macro = np.zeros((B_BOOT, 3))
boot_pc = np.zeros((B_BOOT, 3, K))
base_boot_macro = np.zeros((B_BOOT, 3))
for s, pr in enumerate(pairs):
    n_ph = pr["ph"].max() + 1
    by_class = [np.flatnonzero(pr["ph_class"] == c) for c in range(K)]
    for bi in range(B_BOOT):
        mult = np.zeros(n_ph)
        for idx in by_class:
            draw = RNG.choice(idx, size=len(idx), replace=True)
            np.add.at(mult, draw, 1)
        w = mult[pr["ph"]]
        fb = f1s(pr["y"], pr["pb"], K, w)
        fn = f1s(pr["y"], pr["pn"], K, w)
        boot_pc[bi, s] = fn - fb
        boot_macro[bi, s] = fn.mean() - fb.mean()
        base_boot_macro[bi, s] = fb.mean()
obs_pc = np.array([f1s(pr["y"], pr["pn"], K) - f1s(pr["y"], pr["pb"], K) for pr in pairs])
obs_macro = obs_pc.mean(axis=1)
mean_macro_boot = boot_macro.mean(axis=1)
se = mean_macro_boot.std()
lo, hi = np.quantile(mean_macro_boot, [0.025, 0.975])
out(f"    mean paired delta, test macro-F1: {obs_macro.mean():+.4f}; bootstrap SE {se:.4f}; percentile 95% CI "
    f"[{lo:+.4f}, {hi:+.4f}]")
for s, pr in enumerate(pairs):
    out(f"      seed {pr['seed']:>3}: delta {obs_macro[s]:+.4f}, bootstrap SE {boot_macro[:, s].std():.4f}; "
        f"SE of the baseline's own macro-F1 {base_boot_macro[:, s].std():.4f}")
sd3 = np.std(obs_macro, ddof=1)
out(f"    for comparison, the three deltas' own SD {sd3:.4f}, SE of their mean {sd3/np.sqrt(3):.4f}, t(2) 95% CI "
    f"[{obs_macro.mean() - 4.303*sd3/np.sqrt(3):+.4f}, {obs_macro.mean() + 4.303*sd3/np.sqrt(3):+.4f}]")
out("    per class, mean paired delta over the seeds with its bootstrap 95% CI and SE:")
pc_mean_boot = boot_pc.mean(axis=1)
pc_se = pc_mean_boot.std(axis=0)
for c in range(K):
    lo, hi = np.quantile(pc_mean_boot[:, c], [0.025, 0.975])
    out(f"      {classes[c]:10s} {obs_pc[:, c].mean():+.3f}  [{lo:+.3f}, {hi:+.3f}]  SE {pc_se[c]:.3f}")
out()

# ---------------------------------------------------------------- D
base_f1 = np.array([[metrics(e)["splits"]["test"]["per_class"][c]["f1"] for c in classes] for e in BASE])
base_rng_c = base_f1.max(0) - base_f1.min(0)
base_macro = np.array([metrics(e)["splits"]["test"]["macro_f1"] for e in BASE])
base_rng_macro = base_macro.max() - base_macro.min()


def simulate(plant: tuple[int, int] | None = None, b: int = B_NULL):
    """Per-seed per-class deltas under photo-level arm swapping; optionally plant a drop (class, k photos)."""
    d = np.zeros((b, 3, K))
    for s, pr in enumerate(pairs):
        n_ph = pr["ph"].max() + 1
        pn = pr["pn"].copy()
        if plant is not None:
            c, k = plant
            cm = np.zeros((K, K))
            np.add.at(cm, (pr["y"], pr["pb"]), 1)
            cm[c, c] = -1
            target = int(np.argmax(cm[c]))
            cls_ph = np.flatnonzero(pr["ph_class"] == c)
            # the k photos the baseline gets most right, so the plant is a real loss
            acc = np.array([np.mean(pr["pb"][pr["ph"] == q] == c) for q in cls_ph])
            chosen = cls_ph[np.argsort(-acc, kind="stable")[:k]]
            pn[np.isin(pr["ph"], chosen)] = target
        for bi in range(b):
            swap_ph = RNG.random(n_ph) < 0.5
            sw = swap_ph[pr["ph"]]
            a = np.where(sw, pn, pr["pb"])
            bb = np.where(sw, pr["pb"], pn)
            if plant is None:
                d[bi, s] = f1s(pr["y"], bb, K) - f1s(pr["y"], a, K)
            else:
                # with a planted drop the arms are not exchangeable: keep them, resample photos instead
                pass
        if plant is not None:
            by_class = [np.flatnonzero(pr["ph_class"] == c) for c in range(K)]
            for bi in range(b):
                mult = np.zeros(n_ph)
                for idx in by_class:
                    np.add.at(mult, RNG.choice(idx, size=len(idx), replace=True), 1)
                w = mult[pr["ph"]]
                d[bi, s] = f1s(pr["y"], pn, K, w) - f1s(pr["y"], pr["pb"], K, w)
    return d


def rules(d: np.ndarray) -> dict[str, np.ndarray]:
    """Each rule's per-draw verdict 'a class regressed' (any class), d: (b, 3 seeds, K)."""
    mean_d = d.mean(axis=1)
    r = {}
    r["mean delta < -(baseline per-class seed range)"] = (mean_d < -base_rng_c).any(1)
    r["any seed's delta < -(baseline per-class seed range)"] = (d < -base_rng_c[None, None, :]).any(axis=(1, 2))
    r["new arm's mean F1 < baseline's lowest seed"] = ((base_f1.mean(0)[None, :] + mean_d) < base_f1.min(0)[None, :]).any(1)
    r["all three deltas < 0 (ADR 0002's sign agreement)"] = (d < 0).all(axis=1).any(1)
    for m in (0.01, 0.02, 0.03, 0.05):
        r[f"mean delta < -{m:.2f}"] = (mean_d < -m).any(1)
    r["all three deltas < 0 and mean delta < -0.02"] = ((d < 0).all(axis=1) & (mean_d < -0.02)).any(1)
    r["all three deltas < 0 and mean delta < -0.03"] = ((d < 0).all(axis=1) & (mean_d < -0.03)).any(1)
    return r


out("D. False alarms under no real change: P10's two arms swapped photo by photo at random "
    f"({B_NULL} draws); a rule fires if any of the {K} classes fails it")
out("   the baseline's per-class seed ranges (exp286-288): " + ", ".join(f"{classes[c]} {base_rng_c[c]:.3f}" for c in range(K)))
dnull = simulate()
null_macro = dnull.mean(axis=2).mean(axis=1)
out(f"   null spread of the mean paired delta in test macro-F1: SD {null_macro.std():.4f}, 2.5th pct {np.quantile(null_macro, .025):+.4f}")
out(f"   overall: mean delta < -(baseline macro-F1 seed range, {base_rng_macro:.4f}) fires {np.mean(null_macro < -base_rng_macro):.1%}; "
    f"< -0.005 fires {np.mean(null_macro < -0.005):.1%}; < -0.01 fires {np.mean(null_macro < -0.01):.1%}")
null_pc_mean = dnull.mean(axis=1)
out("   per-class null SD of the mean delta: " + ", ".join(f"{classes[c]} {null_pc_mean[:, c].std():.3f}" for c in range(K)))
out("   family-wise false-alarm rate of each per-class rule:")
null_r = rules(dnull)
for k, v in null_r.items():
    out(f"     {v.mean():6.1%}  {k}")
out("   the same rules on P10's actual deltas (exp289-291 vs exp286-288): " +
    "; ".join(f"{k}: {'FIRES' if rules(obs_pc[None])[k][0] else 'quiet'}" for k in null_r))
out()

# ---------------------------------------------------------------- E
out("E. Power: a real drop planted in one class's new arm (k of its test photos wholly turned to its main confusion),")
out(f"   the photos resampled within class ({B_NULL // 4} draws a cell); share of draws in which each rule fires")
for cname in ("Kenya", "Colombia", "Brazil"):
    c = classes.index(cname)
    for k in (1, 2, 3):
        dp = simulate(plant=(c, k), b=B_NULL // 4)
        md = dp.mean(axis=1)[:, c]
        allneg = (dp[:, :, c] < 0).all(axis=1)
        verdict = {
            "mean < -seed range": md < -base_rng_c[c],
            "all three < 0": allneg,
            "mean < -0.02": md < -0.02,
            "mean < -0.03": md < -0.03,
            "all three < 0 and mean < -0.02": allneg & (md < -0.02),
            "mean < -0.02 and 95% CI below 0": (md < -0.02) & (md + 1.96 * md.std() < 0),
        }
        out(f"   {cname:9s} k={k}: its mean delta {np.median(md):+.3f} (median); fires on that class: " +
            "; ".join(f"{name}: {v.mean():.0%}" for name, v in verdict.items()))
out()

# ---------------------------------------------------------------- F
out("F. The proposed bar applied to P10's pair, test and val; photo-level answers; sensitivity to a larger refit jitter")


def photo_answers(e: int, split: str):
    rows = list(csv.DictReader(open(exp_dir(e) / f"predictions_{split}.csv")))
    cl = metrics(e)["class_ids"]
    acc = defaultdict(list)
    truth = {}
    for r in rows:
        k = (r["true_label"], r["folder_id"], r["photo"])
        acc[k].append([float(r[f"p_{c}"]) for c in cl])
        truth[k] = r["true_label"]
    return {k: (cl[int(np.argmax(np.mean(v, axis=0)))] == truth[k]) for k, v in acc.items()}


for split in ("test", "val"):
    deltas, boots = [], []
    flips = []
    for n, b in zip(NEW, BASE):
        cb, yb, pb, kb = load_preds(b, split)
        cn, yn, pn, kn = load_preds(n, split)
        assert kb == kn
        pid = {k: i for i, k in enumerate(dict.fromkeys(kb))}
        ph = np.array([pid[k] for k in kb])
        phc = np.zeros(len(pid), dtype=int)
        phc[ph] = yb
        by_class = [np.flatnonzero(phc == c) for c in range(K)]
        deltas.append(f1s(yb, pn, K).mean() - f1s(yb, pb, K).mean())
        bs = np.zeros(B_BOOT)
        for bi in range(B_BOOT):
            mult = np.zeros(len(pid))
            for idx in by_class:
                np.add.at(mult, RNG.choice(idx, size=len(idx), replace=True), 1)
            w = mult[ph]
            bs[bi] = f1s(yb, pn, K, w).mean() - f1s(yb, pb, K, w).mean()
        boots.append(bs)
        ab, an = photo_answers(b, split), photo_answers(n, split)
        flips.append((sum(ab.values()), sum(an.values()), len(ab),
                      sum(ab[k] and not an[k] for k in ab), sum(an[k] and not ab[k] for k in ab)))
    m = np.mean(deltas)
    bm = np.mean(boots, axis=0)
    lo = np.quantile(bm, 0.025)
    out(f"  {split}: mean paired delta {m:+.4f}, bootstrap 95% CI [{lo:+.4f}, {np.quantile(bm, .975):+.4f}], SE {bm.std():.4f}; "
        f"non-inferior at margin 0.01: {'yes' if lo > -0.01 else 'NO'}; at 0.005: {'yes' if lo > -0.005 else 'NO'}")
    for (s_, (rb, rn, nn, rw, wr)) in zip(SEEDS, flips):
        out(f"    seed {s_:>3}: photos right (mean of the patch probabilities) {rb}/{nn} -> {rn}/{nn}; right->wrong {rw}, wrong->right {wr}")

out("  Sensitivity: the per-class null of section D with every class's SD scaled (normal approximation,")
out("  seeds and classes independent); family-wise false-alarm rate of the proposed per-class flag and its parts")
sd_seed = dnull.std(axis=0)  # (3, K) per-seed per-class null SD
md_sd = dnull.mean(axis=1).std(axis=0)  # (K,) SD of the class's mean delta
for scale in (1.0, 1.5, 2.0, 3.0):
    z = RNG.standard_normal((20000, 3, K)) * sd_seed[None] * scale
    md = z.mean(axis=1)
    allneg = (z < 0).all(axis=1)
    allneg = allneg & (sd_seed > 0).all(axis=0)[None, :]
    out(f"    x{scale:.1f}: mean < -0.02: {np.mean((md < -0.02).any(1)):.1%}; all three < 0: {np.mean(allneg.any(1)):.1%}; "
        f"both: {np.mean((allneg & (md < -0.02)).any(1)):.1%}; mean < -0.03: {np.mean((md < -0.03).any(1)):.1%}; "
        f"mean < -0.02 and 95% CI below 0: {np.mean(((md < -0.02) & (md + 1.96 * md_sd[None] * scale < 0)).any(1)):.1%}; "
        f"overall mean delta's 95% lower bound < -0.01: {np.mean(z.mean(axis=2).mean(axis=1) - 1.96 * null_macro.std() * scale < -0.01):.2%}")
out()

