"""The ticket board, docs/tickets.html, generated from the tickets: one row per ticket with its ID, its title (the
ticket's <title>), the text of its Status pill and a link to its plan (ADR 0039). Nobody edits the board by hand.

    python -m coffeecv.ticket_board --staged   # .githooks/pre-commit: the board in the index from the staged
                                               # tickets, and the one on disk from the tickets on disk
    python -m coffeecv.ticket_board --write    # the board on disk, from the tickets on disk (a preview)
    python -m coffeecv.ticket_board --check    # scripts/check.sh: fails if the board on disk is not the generated one

A ticket with no eyebrow ID, no <title> or no Status pill cannot have a row: that is a finding, and nothing is
written. Standard library only, in about 0.1 s, so it runs on every commit.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

from coffeecv.ticket_check import _FILE, _STATUS, _TICKET_ID, REPO_ROOT, Finding

BOARD = "tickets.html"
_TITLE = re.compile(r"<title>([^<]*)</title>")
KINDS = (("ml", "ML &mdash; data, model, training, evaluation"), ("ops", "OPS &mdash; deploy, infrastructure"))

HEAD = """<title>Ticket board</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Sans+Condensed:wght@600;700&family=IBM+Plex+Mono:wght@400;500;600&display=swap">
<link rel="stylesheet" href="tickets.css">

<!-- Generated by `python -m coffeecv.ticket_board` from the tickets; the pre-commit hook rewrites it. Edit the tickets, not this file. -->
<main>
  <div class="eyebrow">Ticket board · coffee-vision · every ticket</div>
  <h1>Every ticket, where it stands, and its plan</h1>
  <p class="lede">One row per ticket, newest first in each table, generated from the tickets at every commit: the
    title is the ticket&rsquo;s short title and the status the text of its Status pill. What is done, with dates and
    commits, is in the ticket. Do not edit this page: change the ticket, and the commit brings its row here
    (<code>coffeecv/ticket_board.py</code>, <a href="adr/0039-the-ticket-board-is-generated-at-every-commit.md">ADR 0039</a>).</p>
"""
FOOT = """  <footer>Conventions: <a href="agents/issue-tracker.md">issue-tracker.md</a>. Terms:
    <a href="../GLOSSARY.md">GLOSSARY.md</a>.</footer>
</main>
"""


def render(docs: dict[str, str]) -> tuple[str, list[Finding]]:
    """(the board, findings) from {file name in docs/: text}; other files than tickets and plans are ignored."""
    rows: dict[str, list[tuple[int, str]]] = {kind: [] for kind, _ in KINDS}
    found: list[Finding] = []
    for name in sorted(docs):
        m = _FILE.fullmatch(name)
        if not m or m.group(2) != "ticket":
            continue
        text = docs[name]
        ids, title, status = _TICKET_ID.findall(text), _TITLE.search(text), _STATUS.search(text)
        missing = [what for what, ok in (("one 'Ticket ML-n/OPS-n' eyebrow", len(ids) == 1),
                                         ("a <title>", title), ("a Status pill", status)) if not ok]
        if missing:
            found.append(Finding(f"docs/{name}", 1, f"no row on the ticket board without {', '.join(missing)}"))
            continue
        status_text = status.group(1).strip()
        pill = "ok" if status_text == "Closed" else "open"
        plan = name.replace("_ticket_", "_plan_", 1)
        plan_cell = f'<a href="{plan}">plan</a>' if plan in docs else "&mdash;"
        kind, number = m.group(1).split("-")
        rows[kind].append((int(number),
                           f'      <tr><td class="id">{ids[0]}</td><td><a href="{name}">{title.group(1).strip()}'
                           f'</a></td><td><span class="pill {pill}">{status_text}</span></td>'
                           f"<td>{plan_cell}</td></tr>"))
    body = ""
    for kind, heading in KINDS:
        table = "\n".join(r for _, r in sorted(rows[kind], reverse=True))
        body += (f"\n  <h2>{heading}</h2>\n  <div class=\"table-wrap\"><table>\n"
                 "    <thead><tr><th>ID</th><th>Ticket</th><th>Status</th><th>Plan</th></tr></thead>\n"
                 f"    <tbody>\n{table}\n    </tbody>\n  </table></div>\n")
    return HEAD + body + "\n" + FOOT, found


def working_tree(root: Path = REPO_ROOT) -> dict[str, str]:
    return {f.name: f.read_text() for f in sorted((root / "docs").glob("*.html"))}


def _git(root: Path, *args: str, stdin: bytes | None = None) -> bytes:
    return subprocess.run(["git", "-C", str(root), *args], input=stdin, capture_output=True, check=True).stdout


def staged(root: Path = REPO_ROOT) -> dict[str, str]:
    """docs/*.html as the index holds them, read with one `git cat-file --batch`."""
    paths = [p for p in _git(root, "ls-files", "-z", "--", "docs/").decode().split("\0")
             if p.endswith(".html") and p.count("/") == 1]
    batch = _git(root, "cat-file", "--batch", stdin="".join(f":{p}\n" for p in paths).encode())
    out, pos = {}, 0
    for p in paths:
        header_end = batch.index(b"\n", pos)
        size = int(batch[pos:header_end].split()[2])
        out[p.removeprefix("docs/")] = batch[header_end + 1:header_end + 1 + size].decode()
        pos = header_end + 1 + size + 1
    return out


def update_staged(root: Path = REPO_ROOT) -> tuple[bool, list[Finding]]:
    """The hook's step: the index gets the board of the staged tickets, the disk the board of the tickets on disk.
    Returns (whether the index's board changed, findings); on a finding nothing is written."""
    index = staged(root)
    board, found = render(index)
    disk_board, disk_found = render(working_tree(root))
    if found or disk_found:
        return False, found or disk_found
    path = root / "docs" / BOARD
    if not path.exists() or path.read_text() != disk_board:
        path.write_text(disk_board)
    if index.get(BOARD) == board:
        return False, []
    blob = _git(root, "hash-object", "-w", "--stdin", stdin=board.encode()).decode().strip()
    _git(root, "update-index", "--add", "--cacheinfo", f"100644,{blob},docs/{BOARD}")
    return True, []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--staged", action="store_true", help="update the board in the index and on disk (the hook)")
    mode.add_argument("--write", action="store_true", help="write the board on disk from the tickets on disk")
    mode.add_argument("--check", action="store_true", help="fail if the board on disk is not the generated one")
    args = ap.parse_args(argv)

    if args.staged:
        changed, found = update_staged()
        note = "docs/tickets.html updated from the staged tickets and added to the commit" if changed else \
            "docs/tickets.html already matches the staged tickets"
    else:
        board, found = render(working_tree())
        path = REPO_ROOT / "docs" / BOARD
        current = path.read_text() if path.exists() else None
        if args.write:
            if current != board:
                path.write_text(board)
            note = "docs/tickets.html written" if current != board else "docs/tickets.html already up to date"
        elif current != board and not found:
            found = [Finding(f"docs/{BOARD}", 1, "not the board the tickets give: run "
                                                 "`python -m coffeecv.ticket_board --write` (the pre-commit hook "
                                                 "does this; was it skipped with --no-verify?)")]
        else:
            note = "docs/tickets.html matches the tickets"
    for f in found:
        print(f)
    if found:
        print(f"ticket_board: {len(found)} finding(s)")
        return 1
    print(f"ticket_board: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
